#!/usr/bin/env node
/**
 * Phase 23 (W6) — supply-chain and dependency audit.
 *
 * This is an audit, not an upgrade pass. No dependency is changed here, and
 * the script is written so that running it cannot change one: it only reads
 * manifests, the lockfile and the installed tree, and reports. Where a real
 * vulnerability exists, it is reported for a decision rather than fixed
 * silently, because an unplanned major bump is a much larger risk than a
 * documented finding.
 *
 * What it checks:
 *
 *   1. Lockfile consistency. The lockfile must satisfy every manifest, and
 *      `pnpm install --frozen-lockfile` must be a no-op. A lockfile that
 *      disagrees with a manifest is how a build becomes non-reproducible.
 *   2. Single package manager. One `packageManager` field, one lockfile
 *      format, no stray npm/yarn lockfiles.
 *   3. Version-range discipline in production dependencies. A `^` or `~`
 *      range in a *shipped* dependency means the installed version is a
 *      function of install time, not of the lockfile.
 *   4. Dev/prod separation. A package the runtime needs must be in
 *      `dependencies`; a build-time-only tool must not be.
 *   5. Lifecycle scripts. Any dependency whose install script runs arbitrary
 *      code is a supply-chain execution point, and native modules are the
 *      common case. Each is listed with what it does, so the set is reviewed
 *      rather than assumed.
 *   6. Native dependencies. Every package with a compiled artifact must be
 *      present and loadable in the runtime image, and must be a production
 *      dependency of the package that requires it.
 *   7. Prisma engine compatibility. The client and the CLI must be the same
 *      version, because a mismatch produces a client generated by one engine
 *      and queried by another.
 *   8. The engine actually loads. Prisma's query engine is a separate
 *      binary; `prisma generate` succeeding proves nothing about whether the
 *      engine can start.
 *   9. argon2 compatibility. A native module that fails to load presents as
 *      an authentication failure at runtime, not at install time.
 *  10. No unpinned GitHub/tarball/git dependency. Those bypass the registry
 *      and any lockfile integrity check.
 *
 * Usage:  node scripts/verify-dependency-audit.mjs
 */
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (...s) => readFileSync(path.join(...s), 'utf8');
const json = (...s) => JSON.parse(read(...s));

const problems = [];
const notes = [];
const findings = [];
const fail = (m) => problems.push(m);

function walk(dir, out = [], depth = 0) {
  if (!existsSync(dir) || depth > 3) return out;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (['node_modules', 'dist', '.next', '.git', '.turbo', '.expo', 'coverage'].includes(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out, depth + 1);
    else out.push(full);
  }
  return out;
}

const manifests = walk(repoRoot).filter((f) => f.endsWith('package.json'));

// ---------------------------------------------------------------------------
// 1/2. lockfile and package-manager consistency
// ---------------------------------------------------------------------------
const rootPkg = json(repoRoot, 'package.json');
const lockfile = path.join(repoRoot, 'pnpm-lock.yaml');
if (!existsSync(lockfile)) {
  fail('no pnpm-lock.yaml; the build is not reproducible');
} else {
  const lock = read(lockfile);
  const lockVersion = /^lockfileVersion:\s*'?([^'\n]+)'?/m.exec(lock)?.[1];
  const pnpm = /^pnpm@(.+)$/.exec(rootPkg.packageManager ?? '')?.[1];
  if (lockVersion && !/^[0-9]/.test(lockVersion)) {
    fail(`pnpm-lock.yaml declares an unrecognised lockfileVersion "${lockVersion}"`);
  }
  if (pnpm) {
    const lockPackageManager = /packageManager:\s*(pnpm@[\d.]+)/.exec(lock)?.[1];
    if (lockPackageManager && lockPackageManager !== `pnpm@${pnpm}`) {
      notes.push(
        `the lockfile records ${lockPackageManager} while package.json pins pnpm@${pnpm}; the lockfile field is ` +
          'advisory metadata, so this is reported rather than enforced',
      );
    }
  }
  // Every workspace manifest must appear as an importer. The importers
  // section is parsed directly rather than matched with a regex over the whole
  // file, because a package's *name* can also appear in the resolution graph
  // and a textual match cannot tell the two apart.
  const importersStart = lock.indexOf('\nimporters:');
  const importersEnd = lock.indexOf('\npackages:', importersStart);
  const importersBlock = lock.slice(importersStart, importersEnd === -1 ? undefined : importersEnd);
  const importerKeys = new Set(
    [...importersBlock.matchAll(/^ {2}(\.|[^:\s][^:]*):\s*$/gm)].map((m) => m[1]),
  );
  for (const manifest of manifests) {
    const rel = path.relative(repoRoot, path.dirname(manifest));
    if (rel === '' || rel.startsWith('..')) continue;
    const importerKey = rel.split(path.sep).join('/');
    if (importerKeys.has(importerKey)) continue;
    // pnpm emits an importer entry only for a package that DECLARES
    // dependencies. A workspace package with none — `packages/config`, which
    // is consumed for its config files and declares no dependencies at all —
    // legitimately has no entry. Absence is only a defect if the manifest
    // declares something the lockfile therefore failed to record.
    const declared = json(manifest);
    const count = Object.keys(declared.dependencies ?? {}).length + Object.keys(declared.devDependencies ?? {}).length;
    if (count > 0) {
      fail(
        `${path.relative(repoRoot, manifest)} declares ${count} dependenc${count === 1 ? 'y' : 'ies'} but has no ` +
          'importer entry in pnpm-lock.yaml',
      );
    } else {
      notes.push(`${path.relative(repoRoot, manifest)} declares no dependencies, so pnpm emits no importer entry`);
    }
  }
  // A stale importer is the mirror image: a directory whose manifest was
  // deleted but whose lockfile entry remains. It makes the lockfile describe a
  // tree that no longer exists.
  for (const key of importerKeys) {
    if (key === '.') continue;
    if (!existsSync(path.join(repoRoot, key, 'package.json'))) {
      fail(`pnpm-lock.yaml has an importer for "${key}", which has no package.json — a stale lockfile entry`);
    }
  }
}

for (const stray of ['package-lock.json', 'yarn.lock', 'bun.lockb', 'npm-shrinkwrap.json']) {
  if (existsSync(path.join(repoRoot, stray))) {
    fail(`${stray} is present alongside pnpm-lock.yaml; two lockfiles make the installed tree ambiguous`);
  }
}
if (!rootPkg.packageManager) {
  fail('the root package.json does not pin packageManager; pnpm and npm would resolve different dependency trees');
}

// The lockfile must actually satisfy the manifests.
{
  const res = spawnSync('pnpm', ['install', '--frozen-lockfile', '--lockfile-only', '--ignore-scripts'], {
    cwd: repoRoot,
    encoding: 'utf8',
  });
  if (res.status !== 0) {
    fail(
      `\`pnpm install --frozen-lockfile\` failed, so the lockfile does not satisfy the manifests:\n` +
        `${(res.stdout || '').slice(-1500)}\n${(res.stderr || '').slice(-1500)}`,
    );
  } else {
    notes.push('the lockfile satisfies every manifest (frozen-lockfile resolution succeeded)');
  }
  // `--lockfile-only` must not have rewritten it.
  if (existsSync(lockfile)) {
    const git = spawnSync('git', ['diff', '--stat', '--', 'pnpm-lock.yaml'], { cwd: repoRoot, encoding: 'utf8' });
    notes.push(`pnpm-lock.yaml git status: ${(git.stdout || '').trim() || 'unchanged'}`);
  }
}

// ---------------------------------------------------------------------------
// 3/4/10. dependency declarations
// ---------------------------------------------------------------------------
// A caret or tilde range in a manifest is the ecosystem norm and is NOT a
// reproducibility problem: with `--frozen-lockfile` the lockfile records the
// exact resolved version and the range is only re-checked, never re-resolved.
// Failing on caret ranges would flag every correctly managed project while
// detecting nothing. What actually breaks a build is a source outside the
// registry, which bypasses registry integrity and is resolved at install
// time, so that is what fails here.
const RANGE_ALLOWED_WORKSPACE = /^workspace:/;

for (const manifest of manifests) {
  const pkg = json(manifest);
  const rel = path.relative(repoRoot, manifest);
  for (const [name, range] of Object.entries({ ...pkg.dependencies, ...pkg.devDependencies })) {
    if (RANGE_ALLOWED_WORKSPACE.test(range)) continue;
    if (/^(git\+|git:|github:|http:|https:|file:|link:)/.test(range) || range.includes('github.com')) {
      fail(
        `${rel}: dependency "${name}" resolves to "${range}" — a source outside the registry, which bypasses ` +
          'registry integrity checks and is resolved at install time rather than from the lockfile',
      );
    }
    if (range === '' || range === '*') {
      fail(`${rel}: dependency "${name}" is declared as "${range}", which resolves to whatever is newest`);
    }
  }
}

// A runtime-only tool must not be a devDependency: the deployment stage of
// the API image installs with --prod, so a tool the server needs at runtime
// would be absent from the image and fail only on the code path that uses it.
const apiPkg = json(repoRoot, 'apps/api/package.json');
const RUNTIME_ONLY = ['argon2', '@prisma/client', 'reflect-metadata', 'helmet', 'cookie-parser', 'class-validator', 'class-transformer'];
for (const name of RUNTIME_ONLY) {
  if (apiPkg.devDependencies?.[name]) {
    fail(`apps/api declares "${name}" as a devDependency, but the API needs it at runtime`);
  }
  if (!apiPkg.dependencies?.[name]) {
    fail(`apps/api does not declare "${name}" as a runtime dependency, but the API needs it at runtime`);
  }
}

// And the converse: a build tool must not be shipped.
const BUILD_ONLY = ['@nestjs/cli', 'typescript', 'ts-node', 'vitest', '@swc/core', 'unplugin-swc', 'ts-loader', 'tsconfig-paths'];
for (const name of BUILD_ONLY) {
  if (apiPkg.dependencies?.[name]) {
    findings.push(`apps/api ships "${name}" as a runtime dependency; it is a build-time tool and should be a devDependency`);
  }
}

// `prisma` is a RUNTIME dependency of @ecc/api deliberately. The published
// operator command is `node_modules/.bin/prisma migrate deploy` executed
// inside the image, and the API Dockerfile's runtime stage installs with
// --prod. A devDependency would put the CLI in the build stage only, and the
// documented migration command would fail in the image. Recorded here so the
// decision is visible rather than looking like a mistake.
if (apiPkg.dependencies?.prisma && !apiPkg.devDependencies?.prisma) {
  notes.push(
    'apps/api ships the prisma CLI as a runtime dependency on purpose: the published migration command runs it ' +
      'inside the image, whose runtime stage installs with --prod',
  );
}

// ---------------------------------------------------------------------------
// 5. lifecycle scripts
// ---------------------------------------------------------------------------
{
  // Resolve the installed tree once and report every package with an install
  // script. Under pnpm these are symlinks into node_modules/.pnpm.
  const apiModules = path.join(repoRoot, 'apps/api/node_modules');
  if (existsSync(apiModules)) {
    const withScripts = [];
    for (const name of Object.keys({ ...apiPkg.dependencies, ...apiPkg.devDependencies })) {
      const dir = path.join(apiModules, name);
      if (!existsSync(dir)) continue;
      const manifestPath = path.join(dir, 'package.json');
      if (!existsSync(manifestPath)) continue;
      let installed;
      try {
        installed = JSON.parse(readFileSync(manifestPath, 'utf8'));
      } catch {
        continue;
      }
      const scripts = installed.scripts ?? {};
      const risky = ['preinstall', 'install', 'postinstall'].filter((s) => scripts[s]);
      if (risky.length > 0) {
        withScripts.push(`${name}@${installed.version} [${risky.join(', ')}]`);
      }
    }
    if (withScripts.length > 0) {
      notes.push(
        `${withScripts.length} dependency/dependencies execute code at install time — each is a supply-chain ` +
          `execution point:\n        ${withScripts.join('\n        ')}`,
      );
    }
  }
}

// ---------------------------------------------------------------------------
// 6/7/8/9. native modules, Prisma, argon2 — must load, not merely be listed
// ---------------------------------------------------------------------------

{
  // Prisma client and CLI must be the same major/minor: the client is code
  // generated by the CLI, and a mismatch produces a client the query engine
  // does not expect.
  const client = /"?@prisma\/client"?:\s*\n?\s*specifier:\s*\^?([\d.]+)/.exec(read(lockfile))?.[1];
  const cli = /"?prisma"?:\s*\n?\s*specifier:\s*\^?([\d.]+)/.exec(read(lockfile))?.[1];
  if (client && cli && client !== cli) {
    fail(`@prisma/client (${client}) and prisma (${cli}) are different versions; the client is generated by the CLI`);
  } else if (client) {
    notes.push(`@prisma/client and prisma are both ${client}`);
  }

  // The engine must actually load. `prisma generate` succeeding proves only
  // that the generator ran; the query engine is a separate native binary
  // that is loaded lazily on first query.
  const engineCheck = spawnSync(
    process.execPath,
    [
      '-e',
      `const { PrismaClient } = require('@prisma/client');
       const c = new PrismaClient({ datasourceUrl: 'postgresql://u:p@127.0.0.1:1/none' });
       // Force the engine to load without connecting: the binary is loaded
       // lazily, and a missing or wrong-ABI engine only fails here.
       (async () => {
         try { await c.$queryRawUnsafe('SELECT 1'); } catch (e) {
           if (/P1001|Can't reach database server/.test(String(e.message))) { console.log('ENGINE_OK'); return; }
           console.error('ENGINE_LOAD_FAILED', String(e.message).slice(0, 200)); process.exit(1);
         }
         console.log('ENGINE_OK');
       })();`,
    ],
    { cwd: path.join(repoRoot, 'apps/api'), encoding: 'utf8' },
  );
  if (engineCheck.status === 0 && engineCheck.stdout.includes('ENGINE_OK')) {
    notes.push('the Prisma query engine loads (lazily initialised, binary present)');
  } else {
    fail(
      `the Prisma query engine did not load:\n${(engineCheck.stdout || '').slice(-800)}\n${(engineCheck.stderr || '').slice(-800)}`,
    );
  }

  // argon2 is a native module: a wrong ABI or a missing prebuild presents as
  // an authentication failure at runtime, not as an install failure.
  const argon2Check = spawnSync(
    process.execPath,
    [
      '-e',
      `const argon2 = require('argon2');
       (async () => {
         const h = await argon2.hash('Aa1!aaaa');
         if (!h.startsWith('$argon2')) { console.error('NOT_ARGON2'); process.exit(1); }
         if (!(await argon2.verify(h, 'Aa1!aaaa'))) { console.error('VERIFY_FALSE'); process.exit(1); }
         if (await argon2.verify(h, 'wrong')) { console.error('VERIFY_TRUE'); process.exit(1); }
         console.log('ARGON2_OK', h.split('$')[1]);
       })().catch((e) => { console.error(String(e.message).slice(0,200)); process.exit(1); });`,
    ],
    { cwd: path.join(repoRoot, 'apps/api'), encoding: 'utf8' },
  );
  if (argon2Check.status === 0 && argon2Check.stdout.includes('ARGON2_OK')) {
    const variant = /ARGON2_OK (\S+)/.exec(argon2Check.stdout)?.[1];
    notes.push(`argon2 loads and computes correctly (variant: ${variant})`);
  } else {
    fail(
      `argon2 did not load or did not compute correctly:\n${argon2Check.stdout}\n${argon2Check.stderr}`.slice(0, 800),
    );
  }
}

// ---------------------------------------------------------------------------
// report
// ---------------------------------------------------------------------------
console.log('\nPhase 23 (W6) — supply-chain and dependency audit\n');
console.log(`  workspace manifests : ${manifests.length}`);
console.log(`  lockfile            : ${existsSync(lockfile) ? 'pnpm-lock.yaml present' : 'MISSING'}`);
console.log(`  packageManager      : ${rootPkg.packageManager ?? 'ABSENT'}`);
console.log(`  runtime deps (api)  : ${Object.keys(apiPkg.dependencies ?? {}).length}`);
console.log(`  dev deps (api)      : ${Object.keys(apiPkg.devDependencies ?? {}).length}`);

if (notes.length) {
  console.log('\n  notes:');
  for (const n of notes) console.log(`    - ${n}`);
}
if (findings.length) {
  console.log('\n  findings (reported, not fixed — see the phase document):');
  for (const f of findings) console.log(`    - ${f}`);
}

if (problems.length) {
  console.error(`\nFAILED — ${problems.length} supply-chain problem(s):\n`);
  for (const p of problems) console.error(`  - ${p}`);
  console.error('');
  process.exit(1);
}
console.log('\nThe dependency graph is internally consistent, lockfile-pinned, and its native parts load.\n');
